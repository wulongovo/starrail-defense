  for (const map of MAPS) assert.equal(getStage(map.id, 1).mapId, map.id);
  pass('five destinations rebuild six rows, ten columns, themes and final boss assignments');
  await page.click('[data-mode="blindbox"]');
  await page.click('#start-btn'); await page.click('#begin-battle');
  const boxJade = await page.evaluate(() => window.wulongGame.engine.jade);
