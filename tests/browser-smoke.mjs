  assert.equal(await page.evaluate(() => window.wulongGame.engine.jade), startingJade - CHARACTERS.robin.cost);
  pass('story start and real canvas raycast deploy Robin with correct cost');
  await page.click('[data-character="trailblazer"]');
  await page.click('[data-form="preservation"]');
  await cell(1, 3);
  assert.equal(await page.evaluate(() => window.wulongGame.engine.units.find(u => u.type === 'preservation')?.hp), CHARACTERS.preservation.hp);
  pass('form picker deploys real Preservation with doubled HP');
  await page.keyboard.press('Space');
  assert.equal(await page.evaluate(() => window.wulongGame.engine.status), 'paused');
  const time = await page.evaluate(() => window.wulongGame.engine.time);
  await page.waitForTimeout(220);
  assert.equal(await page.evaluate(() => window.wulongGame.engine.time), time);
  await page.click('#resume-btn');
  assert.equal(await page.evaluate(() => window.wulongGame.engine.status), 'playing');
  pass('pause and resume freeze simulation time');
  await page.click('#remove-btn'); await cell(0, 0);
  assert.equal(await page.evaluate(() => window.wulongGame.engine.units.some(u => u.type === 'robin')), false);
  pass('canvas removal frees an occupied tile');
  await page.click('[data-map="penacony"]'); await page.click('#confirm-mission');
  assert.equal(await page.evaluate(() => window.wulongGame.engine.rows), 6);
  await page.screenshot({ path: join(evidence, 'penacony.png'), fullPage: true });
  await page.click('[data-map="amphoreus"]');
  assert.equal(await page.evaluate(() => window.wulongGame.engine.rows), 6);
  assert.equal(await page.evaluate(() => window.wulongGame.engine.cols), 10);
  await page.screenshot({ path: join(evidence, 'amphoreus.png'), fullPage: true });
  await page.click('[data-map="xianzhou"]');
